#!/usr/bin/env python3
"""Run the stage-1 differential harness (`make check-e2e`).

docs/E2E.md sec 6 stage 1.  Boot maux, let `sh` drive the generated
corpus, pull every result back off the image with `a2til mirror`, and
compare each one against what the host's own `/usr/bin/<tool>` produced
on the same input.

THIS SCRIPT HOLDS NO EXPECTATIONS.  Every "want" it prints came from a
host reference run moments earlier (scripts/e2e_corpus.Case.reference).
docs/E2E.md sec 4's rule -- no expected-output file in this corpus may be
generated by running maux -- is structural here, not a promise: there is
nowhere for a recorded expectation to live.

What may legitimately differ is enumerated one entry at a time in
scripts/e2e_divergence.DIVERGENCE, and this script refuses to start if a
case cites an entry that does not exist, or if an entry exists that no
case needs.  An unexplained difference is a FAILURE.

WARM RESPAWN COMES FREE.  Every tool runs several times in one boot, so
all but its first invocation is served out of a bank the previous run
left behind -- docs/E2E.md sec 3's stage-3 default, arriving early
because a corpus that exercises a tool once was never going to be the
shape of this thing.
"""
import glob
import os
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mcp_drive import MCPClient, SUPERVISOR, ROMS_DIR  # noqa: E402
import e2e_compare as C     # noqa: E402
import e2e_corpus as CORP   # noqa: E402
import e2e_divergence as D  # noqa: E402
from build_e2e_image import HOSTDIR, MIRRORDIR, mirror  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DISK = os.path.join(ROOT, 'build', 'e2e.po')

# Result addresses in the parent process bank -- src/test/e2etestb.s.
R_SCRIPT_FD = 0x1200
R_SH_PID = 0x1201
R_SH_WAIT = 0x1202
R_SH_STATUS = 0x1203
R_DONE = 0x1290
R_ERR = 0x1291
R_STEP = 0x1292

STEP_CYCLES = 5_000_000
MAX_STEPS = 2000


def peek_aux1(client, addr, count=1):
    return client.call_tool('peek', {
        'addr': addr, 'count': count, 'bank': 'aux', 'aux_bank': 1,
    })['bytes']


def pulled(name):
    """Read a file `a2til mirror` pulled back, whatever suffix its ProDOS
    type earned it.  A cadius `#TTAAAA` suffix on a RESULT is itself
    information -- it means maux did not create a TXT file -- so it is
    reported rather than quietly accepted.  `#040000` IS TXT and is the
    name the pre-staged status log keeps (mirror holds a pair's host
    name stable across passes via its sidecar), so it is not flagged."""
    for candidate in (name, f'{name}#040000'):
        path = os.path.join(MIRRORDIR, candidate)
        if os.path.exists(path):
            with open(path, 'rb') as fh:
                return fh.read(), None
    hits = sorted(glob.glob(os.path.join(MIRRORDIR, f'{name}#*')))
    if not hits:
        return None, f'{name} was not created on the volume at all'
    with open(hits[0], 'rb') as fh:
        return fh.read(), (f'{name} came back as {os.path.basename(hits[0])} '
                           f'-- not a ProDOS TXT file')


def run_emulator(disk):
    env = dict(os.environ)
    env['VERILOGAPPLE_ROMS'] = ROMS_DIR
    client = MCPClient([SUPERVISOR], env)
    try:
        client.initialize()
        r = client.call_tool('reset', {'backend': 'fast'})
        print(f'[check-e2e] reset -> {r}', file=sys.stderr)
        r = client.call_tool('mount_disk', {'path': os.path.abspath(disk)})
        print(f'[check-e2e] mount_disk -> {r}', file=sys.stderr)
        if r.get('ok') is False:
            raise RuntimeError(f'mount_disk failed: {r}')
        t0 = time.time()
        done = 0
        for i in range(MAX_STEPS):
            client.call_tool('step', {'cycles': STEP_CYCLES})
            done = peek_aux1(client, R_DONE)[0]
            if done in (0xAA, 0xEE):
                break
        elapsed = time.time() - t0
        state = {
            'done': done,
            'err': peek_aux1(client, R_ERR)[0],
            'step': peek_aux1(client, R_STEP)[0],
            'sh_pid': peek_aux1(client, R_SH_PID)[0],
            'sh_wait': peek_aux1(client, R_SH_WAIT)[0],
            'sh_status': peek_aux1(client, R_SH_STATUS)[0],
            'steps': i + 1,
            'seconds': elapsed,
        }
        return state
    finally:
        client.close()


def main():
    disk = sys.argv[1] if len(sys.argv) > 1 else DISK

    # -- the ratchet's own invariants, before anything is booted -------
    errs, dead = D.check_citations(CORP.CASES)
    for e in errs:
        print(f'[check-e2e] FAIL: {e}', file=sys.stderr)
    for d in dead:
        print(f'[check-e2e] FAIL: divergence entry {d} is cited by no '
              f'case -- the ratchet only tightens; delete it or use it',
              file=sys.stderr)
    if errs or dead:
        return 1

    if not os.path.exists(SUPERVISOR):
        print(f'error: mcp_supervisor not found at {SUPERVISOR}',
              file=sys.stderr)
        return 2
    for path, what in ((disk, 'run `make e2e-image` first'),
                       (HOSTDIR, 'host fixtures'),
                       (MIRRORDIR, 'mirror staging directory')):
        if not os.path.exists(path):
            print(f'error: {path} not found -- {what}', file=sys.stderr)
            return 2

    state = run_emulator(disk)
    print(f"[check-e2e] done=${state['done']:02X} err=${state['err']:02X} "
          f"step=${state['step']:02X} sh_pid={state['sh_pid']} "
          f"sh_wait={state['sh_wait']} "
          f"sh_status=${state['sh_status']:02X} "
          f"({state['steps']} x {STEP_CYCLES} cycles, "
          f"{state['seconds']:.1f}s)")

    boot_failures = []
    if state['done'] != 0xAA:
        boot_failures.append(
            f"the harness process did not finish (done=${state['done']:02X}, "
            f"err=${state['err']:02X}, step={state['step']})")
    if state['err'] != 0:
        boot_failures.append(f"R_ERR expected $00, got ${state['err']:02X}")
    if state['sh_pid'] == 0:
        boot_failures.append('SPAWN(SH) returned pid 0')
    if state['sh_wait'] != state['sh_pid']:
        boot_failures.append(
            f"wait pid {state['sh_wait']} != spawn pid {state['sh_pid']}")
    if boot_failures:
        for f in boot_failures:
            print(f'[check-e2e] FAIL: {f}', file=sys.stderr)
        return 1

    # -- pull the results back the way they went in --------------------
    mirror(disk, CORP.IMG_DIR, MIRRORDIR, 'check-e2e')

    notes = []
    status_bytes, note = pulled(CORP.STATUS_NAME)
    if status_bytes is None:
        print(f'[check-e2e] FAIL: {note}', file=sys.stderr)
        return 1
    if note:
        notes.append(note)

    statuses_text, sp = C.decode_maux_text(status_bytes)
    if sp:
        print(f'[check-e2e] FAIL: the exit-status log has {len(sp)} byte(s) '
              f'with bit 7 clear', file=sys.stderr)
        return 1
    try:
        statuses = [int(x) for x in statuses_text.split()]
    except ValueError:
        print(f'[check-e2e] FAIL: unparseable exit-status log '
              f'{statuses_text!r}', file=sys.stderr)
        return 1
    if len(statuses) != len(CORP.CASES):
        print(f'[check-e2e] FAIL: the exit-status log has {len(statuses)} '
              f'entries for {len(CORP.CASES)} cases -- `sh` did not run '
              f'the whole script (statuses: {statuses})', file=sys.stderr)
        return 1

    verdicts, ref_statuses = [], []
    for case in CORP.CASES:
        raw, note = pulled(case.out_name)
        if raw is None:
            # NO OUTPUT FILE IS A LEGITIMATE PINNED SYMPTOM, so this
            # branch has to honour `defect=` the same way C.judge does.
            #
            # Fix 2026-08-27, found by the sh-language section: when sh
            # REFUSES a line -- `( A ; B ) > F`, nested `$( )` -- it
            # never opens the redirect, so the case produces no file at
            # all. Its KNOWN_DEFECTS pin was registered, printed by the
            # runner, and still counted as a failure, because judge() is
            # where absorption lives and this `continue` returns before
            # reaching it. A pin mechanism that only covers cases which
            # produced output cannot pin a refusal, which is the most
            # common shape of a missing feature.
            #
            # DEFECT-FIXED still works from the other side: if a pinned
            # case starts producing a file, this branch is not taken and
            # judge() reports the pin as fixed.
            # MEMBERSHIP, not mere non-None-ness -- the same guard
            # judge() carries, for the same reason: an unregistered key
            # must never absorb anything.
            if case.defect is not None and case.defect not in D.KNOWN_DEFECTS:
                verdicts.append(C.Verdict(
                    case, False,
                    f'defect={case.defect!r} is not a key of '
                    f'e2e_divergence.KNOWN_DEFECTS -- a missing output '
                    f'must never be absorbed by an unregistered pin',
                    kind='MISSING'))
            elif case.defect is not None:
                verdicts.append(C.Verdict(case, True, note, kind='DEFECT'))
            else:
                verdicts.append(C.Verdict(case, False, note, kind='MISSING'))
            ref_statuses.append(None)
            continue
        if note:
            notes.append(note)
        ref_out, ref_err, ref_status, ref_extra = case.reference(HOSTDIR)
        ref_statuses.append(ref_status)
        # Both descriptors are merged by `2>&1` on both sides, so any
        # diagnostic the reference produced belongs in the expectation
        # too -- and any diagnostic maux produced that the reference did
        # not is a FAILURE OF THAT CASE, with its text, rather than a
        # line in a shared sink nobody attributes.
        verdicts.append(C.judge(case, raw, ref_out + ref_err, ref_extra,
                                HOSTDIR))

    ref_statuses = [s if s is not None else -1 for s in ref_statuses]
    lines, nfail = C.format_report(verdicts, statuses, ref_statuses)
    for line in lines:
        print(f'[check-e2e] {line}', file=sys.stderr)
    for n in notes:
        print(f'[check-e2e] note: {n}', file=sys.stderr)

    percase = {}
    for c in CORP.CASES:
        percase[c.tool] = percase.get(c.tool, 0) + 1
    warm = sum(n - 1 for n in percase.values())
    print('[check-e2e] coverage: ' +
          ', '.join(f'{t} {n}' for t, n in sorted(percase.items())) +
          f'  ({warm} of {len(CORP.CASES)} invocations are WARM respawns '
          f'-- the tool ran earlier in this same boot)')

    for key, reason in sorted(D.KNOWN_DEFECTS.items()):
        print(f'[check-e2e] KNOWN DEFECT {key[0]}: {key[1]}')
        print(f'[check-e2e]   {reason}')

    grades = {}
    for (tool, axis), (grade, _r) in D.DIVERGENCE.items():
        grades[grade] = grades.get(grade, 0) + 1
    print(f'[check-e2e] divergence ratchet: ' +
          ', '.join(f'{g} {n}' for g, n in sorted(grades.items())))
    for where, name, value in __import__('e2e_limits').summary():
        print(f'[check-e2e] boundary {name} = {value} ({where})')

    if nfail:
        print(f'[check-e2e] FAIL: {nfail} of {len(CORP.CASES)} cases '
              f'diverge from the host reference with no ratchet entry '
              f'explaining it', file=sys.stderr)
        return 1
    npin = sum(1 for v in verdicts if v.kind == 'DEFECT')
    print(f'[check-e2e] PASS: {len(CORP.CASES) - npin} cases across '
          f'{len(set(c.tool for c in CORP.CASES))} tools agree with '
          f'/usr/bin byte-for-byte (modulo {len(D.DIVERGENCE)} named '
          f'divergence entries) and every exit status matches; '
          f'{npin} case(s) pinned to a KNOWN DEFECT above')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
