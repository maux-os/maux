def peek_aux1(client, addr, count=1):
    return client.call_tool('peek', {
        'addr': addr, 'count': count, 'bank': 'aux', 'aux_bank': 1,
    })['bytes']


def spawn_trail(client, auditor, syms, budget_cycles, slice_cycles=200_000):
    """Drive the boot to completion, recording EVERY spawn as
    (pathname, warm) in the order it happened.

    Stops on PRC_LD_FL_IMG -- see this file's own module docstring for
    why that address, and why not check_ld.py's end-of-boot LZ_WARM
    read. `until_pc` tests its condition BEFORE advancing, so calling
    it again while the PC is still on the target returns instantly
    forever (textaudit.TextAuditor.run's own comment) -- the `step`
    after every hit is what makes the next call mean "the NEXT spawn".

    `until_pc` matches a bare 16-bit PC and cannot tell the kernel's
    loader entry from an ordinary userland instruction at the same
    address inside a process's own $0800-based bank
    (learning:01M0MYC6NPJDYT62Q5D1M0SRKX, docs/STICKY.md sec 31's "the
    gate had a defect of its own") -- every hit is checked against
    RAMRD via `auditor.in_kernel()` before being trusted, and impostors
    are counted and stepped past rather than mistaken for a spawn.

    A SECOND, DIFFERENT hazard was found MEASURING this gate (not
    documented anywhere before this): `until_pc` has no sync/opcode-
    fetch boundary gate (confirmed against verilogapple's own
    docs/reloaded/specs/spec-03-run-until.md, which exists specifically
    to fix "mid-instruction PC aliasing" for a NEWER verb `run_until`
    that this codebase does not yet use) -- it matches the CPU's `pc`
    register on ANY bus cycle, including the cycles of a `rts` whose
    OWN address is PRC_LD_FL_IMG's own address minus one. That is
    exactly PRC_ZERO_PG's `rts` (src/kernel/procspawn.s): PRC_ZERO_PG
    sits immediately before PRC_LD_FL_IMG in the source and is called
    (via `jmp`, not `jsr`) from INSIDE every PRC_LD_FL_IMG invocation,
    warm or cold, right before that invocation returns to its caller --
    so after `stz`/`lda`/etc. auto-increment the CPU's internal `pc`
    register past the `rts` opcode's own address, `pc` transiently
    equals PRC_LD_FL_IMG's address again, and `until_pc` reports a
    second, SPURIOUS "hit" for every real one (measured: 12 hits for 6
    real spawns, in perfect alternation, confirmed via `trace_capture`
    -- the spurious row has `sync=0`). A genuine entry's first
    instruction is `stz K_BC_ERR`, a 3-byte absolute STZ; CONFIRM_OFFSET
    is that width, and a genuine hit reaches PRC_LD_FL_IMG+CONFIRM_OFFSET
    (the next real instruction, `lda LZ_WARM`) within a handful of
    cycles with NOTHING artificially stepped in between -- the spurious
    alias, mid-RTS, does not (measured: real hits confirm in 3 cycles,
    aliased ones never reach it within 16). Rejected aliases are counted
    and reported separately from RAMRD impostors, since they are a
    different hazard with a different cause.

    A miss (no hit within one slice) is not necessarily the end of the
    run -- `as` assembling a 14KB module goes a long time between
    spawns -- so a miss only ends the loop once the harness itself
    reports done.
    """
    CONFIRM_OFFSET = 3  # `stz K_BC_ERR` -- PRC_LD_FL_IMG's own first
                        # instruction, absolute addressing (3 bytes) --
                        # see this docstring's own "second hazard".
    confirm_pc = syms['PRC_LD_FL_IMG'] + CONFIRM_OFFSET
    spawns = []
    impostors = 0
    aliased = 0
    total = 0
    while total < budget_cycles:
        r = client.call_tool('until_pc', {
            'pc': syms['PRC_LD_FL_IMG'], 'max_cycles': slice_cycles})
        total += r.get('elapsed', slice_cycles)
        if r.get('hit'):
            if not auditor.in_kernel():
                impostors += 1
                client.call_tool('step', {'cycles': 16})
                total += 16
                continue
            confirm = client.call_tool('until_pc', {
                'pc': confirm_pc, 'max_cycles': 16})
            total += confirm.get('elapsed', 16)
            if not confirm.get('hit'):
                aliased += 1
                client.call_tool('step', {'cycles': 16})
                total += 16
                continue
            warm = auditor.peek(syms['LZ_WARM'], 1)[0] != 0
            raw = auditor.peek(syms['PRC_PATHBUF'], 66)
            n = raw[0]
            path = ('' if n == 0 or n > 64 else
                    ''.join(chr(b & 0x7F) for b in raw[1:1 + n]).upper())
            spawns.append((path, warm))
            client.call_tool('step', {'cycles': 16})
            total += 16
            continue
        if peek_aux1(client, R_DONE)[0] in (0xAA, 0xEE):
            break
    return spawns, impostors, aliased


def main():
    disk = sys.argv[1] if len(sys.argv) > 1 else DISK
    if not os.path.exists(SUPERVISOR):
        print(f'error: mcp_supervisor not found at {SUPERVISOR}',
              file=sys.stderr)
        return 2
    if not os.path.exists(disk):
        print(f'error: {disk} not found -- run `make as-image` first',
              file=sys.stderr)
        return 2
    if not os.path.exists(REF_OBJ):
        print(f'error: {REF_OBJ} not found -- run merlin32 on '
              f'src/test/asmodtest.s first', file=sys.stderr)
        return 2
    if not os.path.exists(REF_PUT_OBJ):
        print(f'error: {REF_PUT_OBJ} not found -- run merlin32 on '
              f'src/test/asputtest.s first', file=sys.stderr)
        return 2
    if not os.path.exists(REF_MULTI_OBJ):
        print(f'error: {REF_MULTI_OBJ} not found -- run merlin32 on '
              f'src/test/asmultitest.s first', file=sys.stderr)
        return 2
    if not os.path.exists(REF_BIG_OBJ):
        print(f'error: {REF_BIG_OBJ} not found -- run '
              f'`make {REF_BIG_OBJ}` (scripts/gen_asbigmod.py + merlin32) '
              f'first', file=sys.stderr)
        return 2
    ref_obj = open(REF_OBJ, 'rb').read()
    ref_multi_obj = open(REF_MULTI_OBJ, 'rb').read()
    ref_put_obj = open(REF_PUT_OBJ, 'rb').read()
    ref_big_obj = open(REF_BIG_OBJ, 'rb').read()
    for f in (REF_RELMOD, REF_RELMAIN, REL_META):
        if not os.path.exists(f):
            print(f'error: {f} not found -- run `make check-rel` first '
                  f'(real Merlin produces the REL references)',
                  file=sys.stderr)
            return 2
    import json
    ref_relmod = open(REF_RELMOD, 'rb').read()
    ref_relmain = open(REF_RELMAIN, 'rb').read()
    rel_meta = json.load(open(REL_META))
    syms = load_syms(SYMFILE, names=('LZ_WARM', 'PRC_LD_FL_IMG',
                                      'PRC_PATHBUF'), binary=SYS_BIN)

    env = dict(os.environ)
    env['VERILOGAPPLE_ROMS'] = ROMS_DIR
    client = MCPClient([SUPERVISOR], env)
    try:
        client.initialize()
        r = client.call_tool('reset', {'backend': 'fast'})
        print(f'[check-as] reset -> {r}', file=sys.stderr)
        r = client.call_tool('mount_disk', {'path': os.path.abspath(disk)})
        print(f'[check-as] mount_disk -> {r}', file=sys.stderr)
        if r.get('ok') is False:
            raise RuntimeError(f'mount_disk failed: {r}')

        # `as` assembling a whole PATCHED core's worth of pass-1/pass-2
        # work (four times via sh -- good, good again (the warm-respawn
        # pair), multi-label, then the P11 big-module proof -- plus a
        # fifth direct spawn on a bad module) needs considerably more
        # budget than a single-spawn util gate. check-ascore's own
        # single-assembly drive alone budgets 80M cycles; this harness
        # boots + spawns sh + spawns AS five times (with a fresh ~9KB
        # core embed each time) on TOP of that. Bumped from 8000*200_000
        # (1.6B) to 14000*200_000 (2.8B) when BIGMOD (2800 NOPs, docs/
        # AS-DESIGN.md section 15/16) was added; bumped AGAIN here to
        # 15500*200_000 (3.1B, +300M/~11%) for the second GOODMOD spawn
        # (docs/STICKY.md sec 31's warm-respawn proof) -- GOODMOD's own
        # assembly is negligible (6 bytes, a single instruction), but a
        # sixth spawn adds a full SPAWN+loader-or-warm-zero-page+WAIT
        # cycle of fixed kernel overhead on top of everything above.
        # Bumped again 2026-08-28 for the PUT case (a SIXTH `as`
        # spawn in the script run): PUTMOD's own assembly is tiny,
        # but the spawn+loader+WAIT overhead is not. And again
        # 2026-08-29 for the TWO REL cases (spawns seven and eight):
        # both modules are tiny (68B and 4B of code) so the cost is
        # again the fixed spawn+loader+WAIT overhead, twice.
        BUDGET_CYCLES = 20000 * 200_000
        auditor = TextAuditor(client, syms, images={}, label='check-as')
        spawns, impostors, aliased = spawn_trail(client, auditor, syms,
                                                 BUDGET_CYCLES)
        done = peek_aux1(client, R_DONE)[0]
        err = peek_aux1(client, R_ERR)[0]
        step = peek_aux1(client, R_STEP)[0]
        sh_pid = peek_aux1(client, R_SH_PID)[0]
        sh_status = peek_aux1(client, R_SH_STATUS)[0]
        as_pid = peek_aux1(client, R_AS_PID)[0]
        as_status = peek_aux1(client, R_AS_STATUS)[0]
        t = peek_aux1(client, R_ASE_TRANS, 2)
        ase_trans = t[0] | (t[1] << 8)
        ase_data = bytes(peek_aux1(client, R_ASE_DATA,
                                   min(ase_trans, RBLEN)))
        print(f'[check-as] done=${done:02X} err=${err:02X} step=${step:02X}'
              f' sh_pid={sh_pid} sh_status=${sh_status:02X}'
              f' as_pid={as_pid} as_status=${as_status:02X}'
              f' ase_trans={ase_trans} ase_data={ase_data!r}')
        print(f'[check-as] spawn trail ({len(spawns)} spawn(s) observed, '
              f'{impostors} userland stop(s) at PRC_LD_FL_IMG\'s address '
              f'rejected as RAMRD impostors, {aliased} mid-instruction PC '
              f'alias(es) from PRC_ZERO_PG\'s own `rts` rejected -- see '
              f'spawn_trail()\'s own docstring):')
        for i, (path, warm) in enumerate(spawns):
            print(f'    {i}: {path or "(unreadable pathname)"}  '
                  f'{"WARM" if warm else "cold"}')

        failures = []
        if done != 0xAA:
            failures.append(f'test did not finish successfully '
                            f'(done=${done:02X}, err=${err:02X}, '
                            f'step={step})')
        if sh_pid == 0:
            failures.append('SPAWN(SH) returned pid 0')
        if sh_status != 0:
            # NOTE (found proving this gate's teeth, task #8 phase C):
            # sh's own EXIT builtin (src/bin/sh.s CHCK_BLTN_EXT) takes an
            # explicit status argument or defaults to 0 -- it does NOT
            # inspect the PRECEDING command's exit status (no `$?` in
            # this shell, SH-DESIGN's own v1 scope). SCRIPT_TEXT always
            # ends with a bare `EXIT`, so sh_status is 0 REGARDLESS of
            # whether any `AS` invocation inside the script succeeded --
            # this assertion can only ever catch sh/SPAWN/WAIT
            # infrastructure failing, never an AS assembly error (that
            # signal is the byte-compares below, which can now also FAIL
            # cleanly instead of crashing if the object was never
            # written -- see those `except` blocks).
            failures.append(f'sh exit status expected $00, got '
                            f'${sh_status:02X} (sh/SPAWN/WAIT '
                            f'infrastructure failure -- NOT necessarily '
                            f'an AS assembly error, see this file\'s own '
                            f'comment here)')
        if as_pid == 0:
            failures.append('direct SPAWN(AS) returned pid 0')
        if as_status == 0:
            failures.append('AS on the syntax-error source exited 0, '
                            'expected nonzero')
        if not ase_data.startswith(bytes([ord('a') | 0x80, ord('s') | 0x80,
                                          ord(':') | 0x80])):
            failures.append(f'AS stderr diagnostic missing the "as: " '
                            f'prefix (high-bit-set): got {ase_data!r}')

        if failures:
            for f in failures:
                print(f'[check-as] FAIL: {f}', file=sys.stderr)
            return 1

        # -- byte compares + the warmness vacuity guard, accumulated
        # -- into ONE failures list (check_ld.py's own shape) so a red
        # -- run reports every half that is actually red, not just the
        # -- first one found.
        failures = []
        vol = a2til.open_image(disk)

        try:
            got_obj = bytes(vol.read_file(f'/mnt/{VOL}/GOODMOD.OBJ'))
        except FileNotFoundError:
            # sh_status can't catch this (see the comment above) -- if
            # GOODMOD.S failed to assemble, MYEXIT never reaches
            # WRITEOBJ and this file simply does not exist. A clean
            # FAIL, not an uncaught traceback (found proving this
            # gate's own teeth, task #8 phase C).
            got_obj = None
            failures.append('/mnt/MAUX/GOODMOD.OBJ does not exist -- AS did '
                            'not write it (assembly likely failed)')
        if got_obj is not None:
            print(f'[check-as] GOODMOD.OBJ: {len(got_obj)}B on-image, '
                  f'{len(ref_obj)}B merlin32 reference')
            if got_obj != ref_obj:
                ndiff = sum(1 for x, y in zip(got_obj, ref_obj) if x != y)
                failures.append(
                    f'GOODMOD.OBJ differs from merlin32 in {ndiff} byte(s) '
                    f'(lengths {len(got_obj)} vs {len(ref_obj)})\n'
                    f'  got={got_obj!r}\n  ref={ref_obj!r}')

        # GOODMOD2.OBJ -- the SECOND, adjacent GOODMOD assembly (docs/
        # STICKY.md sec 31's warm-respawn proof). Compared against the
        # SAME host reference GOODMOD.OBJ is compared against, NEVER
        # against got_obj itself: two identically-wrong outputs must
        # still fail (check_ld.py's own ruling for LDOUT2 vs LDOUT).
        try:
            got_obj2 = bytes(vol.read_file(f'/mnt/{VOL}/GOODMOD2.OBJ'))
        except FileNotFoundError:
            got_obj2 = None
            failures.append(
                '/mnt/MAUX/GOODMOD2.OBJ does not exist -- the SECOND AS '
                'assembly of this boot wrote no output file at all')
        if got_obj2 is not None:
            print(f'[check-as] GOODMOD2.OBJ: {len(got_obj2)}B on-image, '
                  f'{len(ref_obj)}B merlin32 reference (SECOND assembly '
                  f'of this boot)')
            if got_obj2 != ref_obj:
                ndiff = sum(1 for x, y in zip(got_obj2, ref_obj) if x != y)
                failures.append(
                    f'GOODMOD2.OBJ -- the SECOND AS assembly of this boot '
                    f'-- differs from merlin32 in {ndiff} byte(s) (lengths '
                    f'{len(got_obj2)} vs {len(ref_obj)})\n'
                    f'  got={got_obj2!r}\n  ref={ref_obj!r}')

        try:
            got_multi = bytes(vol.read_file(f'/mnt/{VOL}/MULTIMOD.OBJ'))
        except FileNotFoundError:
            got_multi = None
            failures.append('/mnt/MAUX/MULTIMOD.OBJ does not exist -- AS did '
                            'not write it (assembly likely failed)')
        if got_multi is not None:
            print(f'[check-as] MULTIMOD.OBJ: {len(got_multi)}B on-image, '
                  f'{len(ref_multi_obj)}B merlin32 reference')
            if got_multi != ref_multi_obj:
                ndiff = sum(1 for x, y in zip(got_multi, ref_multi_obj)
                            if x != y)
                failures.append(
                    f'MULTIMOD.OBJ (multi-label/forward-ref/:LOCAL) '
                    f'differs from merlin32 in {ndiff} byte(s) (lengths '
                    f'{len(got_multi)} vs {len(ref_multi_obj)})\n'
                    f'  got={got_multi!r}\n  ref={ref_multi_obj!r}')

        # THE PUT CASE (docs/AS-PUT.md). Until AS_GOREAD existed, the
        # core's `JSR GOREAD` landed on unstubbed $E021 and `as` could
        # not service a put at all -- which meant it could not assemble
        # one line of the real maux tree, every unit of which puts liba
        # at minimum. The module is deliberately not trivial: it calls
        # FORWARD into the put'd file, so a put that loaded the wrong
        # bytes cannot match by accident, and it has an `rts` AFTER the
        # put line, which is only reached if the parent's source
        # pointer was restored (ENDPUT, off the $00 terminator
        # AS_GOREAD writes).
        #
        # The image's copy carries an ABSOLUTE put operand
        # (/mnt/MAUX/PUTINC.S, rewritten by build_as_image.py) while the
        # host reference uses the relative one -- the same rewrite
        # build_maux_src_image.py does for the real tree. Two source
        # texts, one object.
        # LIVE since 2026-08-28. ABSENCE IS A FAILURE, not a skip:
        # while this tolerated a missing object the gate would have
        # gone green the moment the put path regressed to the hang it
        # spent a session in -- the exact regression this case exists
        # to catch. It is the one object here whose production is
        # itself the thing under test.
        try:
            got_put = bytes(vol.read_file(f'/mnt/{VOL}/PUTMOD.OBJ'))
        except FileNotFoundError:
            got_put = None
            failures.append(
                'PUTMOD.OBJ was never written -- `as` did not complete '
                'the assembly of a module containing a `put` line. That '
                'is the self-hosting blocker; see docs/AS-PUT.md.')
        if got_put is not None:
            print(f'[check-as] PUTMOD.OBJ: {len(got_put)}B on-image, '
                  f'{len(ref_put_obj)}B merlin32 reference')
            if got_put != ref_put_obj:
                ndiff = sum(1 for x, y in zip(got_put, ref_put_obj)
                            if x != y)
                failures.append(
                    f'PUTMOD.OBJ (a module that PUTs another file) '
                    f'differs from merlin32 in {ndiff} byte(s) (lengths '
                    f'{len(got_put)} vs {len(ref_put_obj)})\n'
                    f'  got={got_put!r}\n  ref={ref_put_obj!r}')

        try:
            got_big = bytes(vol.read_file(f'/mnt/{VOL}/BIGMOD.OBJ'))
        except FileNotFoundError:
            got_big = None
            failures.append('/mnt/MAUX/BIGMOD.OBJ does not exist -- AS did '
                            'not write it (P11 big-module assembly likely '
                            'failed -- see docs/AS-DESIGN.md section '
                            '15/16)')
        if got_big is not None:
            print(f'[check-as] BIGMOD.OBJ: {len(got_big)}B on-image, '
                  f'{len(ref_big_obj)}B merlin32 reference')
            if got_big != ref_big_obj:
                ndiff = sum(1 for x, y in zip(got_big, ref_big_obj)
                            if x != y)
                failures.append(
                    f'BIGMOD.OBJ (boundary-max module, 16127B source) '
                    f'differs from merlin32 in {ndiff} byte(s) (lengths '
                    f'{len(got_big)} vs {len(ref_big_obj)})')

        # THE REL CASES (S9 REL route, docs/S9-PLAN.md sec 6 L0):
        # the same sources real Merlin assembled for check-rel's
        # references, assembled by `as` in-memory (P15 dictionary,
        # WRITEOBJ's REL branch). Byte-identity INCLUDES the
        # dictionary; the ProDOS type must be $F8 and aux the CODE
        # length -- the linker's own contract for where code ends.
        for objname, refname, ref, meta in (
                ('RELMOD.OBJ', 'rtlib.rel', ref_relmod,
                 rel_meta['rtlib']),
                ('RELMAIN.OBJ', 'rtmain.rel', ref_relmain,
                 rel_meta['rtmain'])):
            try:
                got = bytes(vol.read_file(f'/mnt/{VOL}/{objname}'))
                ent = vol.entry_for(f'/mnt/{VOL}/{objname}')
            except FileNotFoundError:
                failures.append(
                    f'/mnt/MAUX/{objname} does not exist -- AS did not '
                    f'write it (REL assembly failed; docs/S9-PLAN.md '
                    f'sec 6 L0)')
                continue
            print(f'[check-as] {objname}: {len(got)}B on-image '
                  f'(type ${ent.type:02X} aux ${ent.aux_type:04X}), '
                  f'{len(ref)}B real-Merlin reference '
                  f'(type ${meta["type"]:02X} aux ${meta["aux"]:04X})')
            if got != ref:
                ndiff = sum(1 for x, y in zip(got, ref) if x != y)
                failures.append(
                    f'{objname} differs from real Merlin\'s {refname} '
                    f'in {ndiff} byte(s) (lengths {len(got)} vs '
                    f'{len(ref)})\n  got={got!r}\n  ref={ref!r}')
            if ent.type != meta['type'] or ent.aux_type != meta['aux']:
                failures.append(
                    f'{objname} ProDOS type/aux ${ent.type:02X}/'
                    f'${ent.aux_type:04X} != real Merlin\'s '
                    f'${meta["type"]:02X}/${meta["aux"]:04X} -- for a '
                    f'REL object aux IS the code length; the linker '
                    f'reads the dictionary from there')

        # THE WARMNESS GUARD, checked AFTER the byte comparisons above
        # (check_ld.py's own ordering) so a red run reports both halves.
        # Find the /bin/AS entries in spawn_trail()'s own order --
        # SH, then AS(GOODMOD), AS(GOODMOD2), AS(MULTIMOD), AS(BIGMOD),
        # then the direct AS(BADMOD) spawn -- and require the SECOND one
        # (GOODMOD2's own spawn) to have been served warm.
        as_idx = [i for i, (path, _warm) in enumerate(spawns)
                  if path == AS_SPAWN_PATH]
        if len(as_idx) < 2:
            failures.append(
                f'expected at least 2 {AS_SPAWN_PATH} spawns in this boot '
                f'(one per GOODMOD line, plus MULTIMOD/BIGMOD/BADMOD), saw '
                f'{len(as_idx)}: {spawns}')
        else:
            i1, i2 = as_idx[0], as_idx[1]
            if i2 != i1 + 1:
                between = [path or "(unreadable pathname)"
                           for path, _warm in spawns[i1 + 1:i2]]
                failures.append(
                    f'the two GOODMOD lines are not adjacent in the '
                    f'boot\'s own spawn order: {between} spawned in '
                    f'between (spawn index {i1} -> {i2}). Adjacency is '
                    f'load-bearing -- anything spawned between them can '
                    f'reclaim the bank and make the second AS cold, which '
                    f'would pass while proving nothing.')
            path2, warm2 = spawns[i2]
            if not warm2:
                failures.append(
                    f'the SECOND {AS_SPAWN_PATH} spawn of this boot (spawn '
                    f'index {i2}, the GOODMOD2 line) was NOT served warm: '
                    f'LZ_WARM was clear at its own PRC_LD_FL_IMG entry. '
                    f'`as` rewrites its own entry head, so the kernel\'s '
                    f'LZ_RETAIN refuses to retain its bank and every `as` '
                    f'spawn in this boot cold-loads -- this is exactly the '
                    f'bug class docs/STICKY.md sec 29/31 describes, and '
                    f'this gate could not see it until now. Full spawn '
                    f'trail: {spawns}')

        if failures:
            for f in failures:
                print(f'[check-as] FAIL: {f}', file=sys.stderr)
            return 1

        print('[check-as] PASS: `as` (spawned from the maux shell via sh) '
              'assembles a single-instruction module TWICE, adjacently -- '
              'the SECOND time served WARM out of the bank the first left '
              'behind -- a multi-label/forward-reference/:LOCAL-label '
              'module, AND a 16127B boundary-max module (the exact '
              'maximum as\'s source window admits -- one more byte is '
              'refused), all to BYTE-IDENTICAL '
              'objects against merlin32 on the host, and a syntax-error '
              'source (direct spawn, fd 2 captured) exits nonzero with an '
              '"as: "-prefixed diagnostic')
        return 0
    finally:
        client.close()


if __name__ == '__main__':
    raise SystemExit(main())
