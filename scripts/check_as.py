#!/usr/bin/env python3
"""Boot and verify the `as` acceptance gate (`make check-as`).

Companion to src/test/astest.s / scripts/build_as_image.py. See
docs/AS-DESIGN.md section 0 for the milestone bar this proves: `as [-l]
[-o obj] src` runs INSIDE maux and produces an object byte-identical to
merlin32 assembling the SAME source on the host.

Two runs (astestb.s's PARENT_PROC):
  1. `sh` (stdin redirected from a staged script) runs FOUR `as`
     commands back to back -- `AS /mnt/MAUX/GOODMOD.S -o /mnt/MAUX/GOODMOD.OBJ`
     (the single-instruction module), THE SAME ASSEMBLY AGAIN,
     ADJACENTLY, into /mnt/MAUX/GOODMOD2.OBJ (docs/STICKY.md sec 31's
     warm-respawn proof -- see spawn_trail()'s own docstring below and
     scripts/build_as_image.py's SCRIPT_TEXT comment), `AS
     /mnt/MAUX/MULTIMOD.S -o /mnt/MAUX/MULTIMOD.OBJ` (src/test/asmultitest.s:
     multiple labels, a forward reference, a Merlin `:LOCAL` label
     referenced backward in a loop -- the module that proved P9 (a
     since-dropped patch, docs/AS-DESIGN.md section 14) unnecessary once
     the real bugs were fixed, reused here so `check-as`'s byte-
     identical bar isn't just a single `lda`/`sta`/`rts` that could pass
     by accident), and `AS /mnt/MAUX/BIGMOD.S -o /mnt/MAUX/BIGMOD.OBJ`
     (build/asbigmod.s, generated by scripts/gen_asbigmod.py -- 16,127B,
     the EXACT maximum flat source as's window admits, verified by
     bracketing 2026-08-29: 16,127 assembles byte-identical, 16,128 is
     refused. An aligned-boundary fixture: if the ceiling regresses by
     one byte this gate goes red -- docs/AS-DESIGN.md section 15/16's
     requirement 5, sharpened from the old ~14KB proof module) -- then `EXIT`.
     All four objects are read back from the built image afterward and
     compared byte-for-byte against their own host-merlin32 reference
     (GOODMOD.OBJ and GOODMOD2.OBJ BOTH against build/asmodtest.bin --
     never GOODMOD2 against GOODMOD.OBJ, so two identically-wrong
     outputs still fail; build/asmultitest.bin; build/asbigmod.bin --
     see the Makefile's rules for all three source files). BIGMOD runs
     LAST so a P11 teeth run (exclude P11 from the embedded core) that
     corrupts its assembly cannot also corrupt the EARLIER, already-
     completed, already-on-disk runs -- isolating the P11 tooth to the
     big-module phase alone.
  2. `AS` spawned DIRECTLY on a source with one deliberate syntax error
     (src/test/asbadmod.s), fd 2 dup'd to a harness-owned file (sh cannot
     do this -- it recognizes only '<'/'>', no `2>`). Asserts a nonzero
     exit status and an "as: "-prefixed diagnostic on the captured
     stderr.

THE WARMNESS GUARD (docs/STICKY.md sec 29/31). `as` rewrites 8,685 of
its 15,968 image bytes per run, entry `jmp` included, so LZ_RETAIN
refuses to retain its bank and it can never be respawned warm -- but
until now `check-as` spawned `as` FOUR times per boot without ever
asserting that any of them were warm, so a gate that is supposed to see
this bug class could not. spawn_trail() below enumerates EVERY spawn of
the boot as (pathname, warm), the same technique scripts/
check_shwarm.py's spawn_warm() already got right (stopping on
PRC_LD_FL_IMG, the kernel's loader entry, reached exactly once per
spawn with LZ_WARM already decided by PRC_ALLC_BANK and PRC_PATHBUF
still holding the canonical pathname being spawned) -- generalized here
to walk the WHOLE boot rather than stopping after a single spawn,
because this gate needs the full ORDERED trail to name which spawn, if
any, landed between the two GOODMOD lines.

This deliberately does NOT use check_ld.py's shape (a single end-of-
boot read of the kernel's global LZ_WARM cell). That cell is stz'd by
PRC_ALLC_BANK and set on the no-copy path ONCE PER SPAWN, so it
describes only the LAST spawn that touched it -- reading it at a
process's own exit describes that process's own spawn only if the
process spawned nothing itself, and even a childless LEAF process can
be misread if some OTHER spawn (a sibling, not a child) lands between
its own spawn and its own exit (learning:01M0NWAK2AQSH42GGGKTRJ2F2Y,
learning:01M0PEVEA9CJ0CVB4CQT4M8V38). Reading it at a spawn's OWN
PRC_LD_FL_IMG entry sidesteps this entirely: this machine is a single
6502 CPU, so PRC_LD_FL_IMG's own `lda LZ_WARM` (src/kernel/procspawn.s)
executes synchronously as part of THAT spawn's SPAWN syscall, before
any other spawn can possibly run -- the value read there is
unambiguously that spawn's own.
"""
