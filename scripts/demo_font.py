class MissingGlyph(KeyError):
    """A character the font does not carry, asked for with strict=True."""


def glyph(ch, strict=False):
    """Return the DEPTH row strings for `ch`, each WIDTH characters of
    '#' and '.'. Anything the font does not carry draws as '?' (the key
    strip's habit) -- unless `strict`, which raises MissingGlyph: text
    the demo author wrote (the popover) must never come out as a
    silent '?' or a blank."""
    rows = _GLYPHS.get(ch)
    if rows is None:
        if strict:
            raise MissingGlyph(
                f'the overlay font has no glyph for {ch!r} (ASCII 32-126 '
                f'only)')
        rows = _GLYPHS['?']
    return rows + (_B,) * (DEPTH - len(rows))


def _selfcheck():
    for ch in (chr(c) for c in range(32, 127)):
        rows = _GLYPHS[ch]
        assert len(rows) in (HEIGHT, DEPTH), ch
        assert all(len(r) == WIDTH and set(r) <= set('#.') for r in rows), ch


_selfcheck()
