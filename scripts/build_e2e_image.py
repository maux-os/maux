#!/usr/bin/env python3
"""Build the stage-1 differential-harness image (`make e2e-image`).

TRANSPORT IS `a2til mirror`, per docs/E2E.md sec 6 stage 1 and HACKING.md's
"knowing a house tool exists is not knowing what it does".  Read a2til's
README feature list and `--help` before touching this file; the recorded
incident is a2til being driven as a bare image-writer with write_file/
mkdir loops and hand-encoded high-bit ASCII when `mirror` and `convert`
already shipped the work.

Which of mirror's features actually do the work here, and why each was
chosen over doing it by hand:

  * `mirror IMAGE:/VOL/DIR LOCALDIR --once` -- one poll-sync pass in each
    direction.  The corpus is generated into a host directory and pushed;
    after the emulator runs, the SAME command pulls every result file
    back out.  Nothing in this harness opens the volume for a file copy.
  * `--raw` -- byte-exact transfer, no converter.  This is deliberate and
    it is the one place a2til's own text translation is declined: a2til's
    ProDOS text converter produces LOW-ASCII with $0D, which is correct
    for ProDOS TXT in general and wrong for maux, whose text is HIGH-BIT
    with $8D.  The encoding still comes from a2til -- `convert.
    text_from_host(high_bit=True)`, the same function its DOS 3.3 path
    uses -- applied once in scripts/e2e_corpus.py.  Translating twice
    would corrupt every fixture; hand-rolling the encoder would repeat
    the recorded mistake.
  * the cadius-style `#040000` host-name suffix -- mirror's own notation
    for "store this raw, as ProDOS type $04 aux $0000".  That is how the
    generated bytes land as TXT files maux's tools will open, without
    this script ever naming a file type.
  * the `.a2til-mirror.json` sidecar -- three-way state, so the pull pass
    correctly reads the inputs as unchanged and the outputs as new,
    rather than conflicting with itself.
  * one transaction per pass -- a failed push rolls the image back whole,
    so a half-staged corpus cannot be run and mistaken for a result.

A SUBDIRECTORY, NOT THE VOLUME ROOT.  mirror syncs BOTH ways; aimed at
/mnt/MAUX it would faithfully pull PRODOS, MAUX.SYSTEM, SH and the nine
binaries out onto the host on its first pass.  The corpus lives in
/mnt/MAUX/E2E and the binaries stay outside it.
"""
import hashlib
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import e2e_corpus as CORP  # noqa: E402

sys.path.insert(0, os.path.expanduser(os.environ.get('A2TIL', '~/src/a2til')))
from a2til import prodos  # noqa: E402
import vpath  # noqa: E402,F401  (docs/VROOT.md: virtual paths for a2til)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, 'build')
CARRIER_IMG = os.environ.get('PRODOS_CARRIER_IMG',
                             os.path.join(ROOT, 'vendor', 'prodos-basic.po'))
CARRIER_VOL = os.environ.get('PRODOS_CARRIER_VOL', 'MAUX')
KERNEL_BIN = os.environ.get('PRODOS_KERNEL_BIN',
                            os.path.join(ROOT, 'vendor', 'ProDOS-2.4.bin'))
SYS_BIN = os.path.join(BUILD, 'MAUXE2E.SYSTEM')
OUT_IMG = os.path.join(BUILD, 'e2e.po')

#: The tools of docs/E2E.md stage 1's first tranche, plus the two
#: programs the harness itself needs: `sh` to run the script and `echo`
#: to append `$?` to the status log.
TOOLS = ['sort', 'diff', 'tr', 'uniq', 'comm', 'wc', 'od', 'cmp', 'sum',
         'cat', 'grep', 'tee', 'expr', 'tail', 'head', 'sed', 'cut',
         'xargs', 'find', 'printf', 'basename', 'dirname', 'env',
         'uuencode', 'uudecode', 'cksum', 'paste', 'fold',
         'nl', 'expand', 'unexpand', 'cal', 'strings',
         'nohup', 'tsort', 'pr', 'pathchk', 'split', 'csplit', 'join']
#: timeout/realpath (eng-nohup-timeout-realpath) are NOT here, same
#: as `man` above them: timeout has no host oracle on this Mac at
#: all, and realpath's base directory is per-case (check_posixutil's
#: own /mnt/MAUX/PXUT/<K-tag> shape), so neither can feed this file's
#: literal-argv/literal-output comparison -- see the task report.
NEEDED = ['sh', 'echo'] + TOOLS

#: Host-form fixtures -- what /usr/bin reads.
HOSTDIR = os.environ.get('E2E_HOSTDIR', os.path.join(BUILD, 'e2e-host'))
#: Image-form fixtures -- what `a2til mirror` pushes, and where it pulls
#: the results back to.  Both are overridable so the transport and the
#: comparison half can be exercised on a COPY of the image, off the rig
#: (`E2E_HOSTDIR`/`E2E_MIRRORDIR`).
MIRRORDIR = os.environ.get('E2E_MIRRORDIR',
                           os.path.join(BUILD, 'e2e-mirror'))

A2TIL_ROOT = os.path.expanduser(os.environ.get('A2TIL', '~/src/a2til'))

#: An 800K ProDOS volume, not the 280-block carrier every other gate
#: copies.  MEASURED, not guessed: with the kernel, `sh`, `echo` and the
#: original stage-1 roster staged, the carrier had only 79 blocks free,
#: and staging the results failed with `no free blocks on volume` --
#: each result is at least one block and ProDOS charges an index block
#: on top for anything over 512 bytes. A corpus that does not fit
#: cannot run; this build prints the current staged bytes and headroom
#: every run instead of baking those moving counts into this comment.
VOL_BLOCKS = 1600
BOOT_BYTES = 1024          # blocks 0 and 1: the ProDOS boot loader


def mirror(image, imgdir, localdir, label):
    """One `a2til mirror --once --raw` pass.  Returns its log lines."""
    argv = [sys.executable, '-m', 'a2til', 'mirror',
            f'{os.path.abspath(image)}:{vpath.phys(imgdir)}', localdir,
            '--once', '--raw', '--interval', '1']
    proc = subprocess.run(argv, cwd=A2TIL_ROOT, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True)
    for line in proc.stdout.splitlines():
        print(f'[{label}] mirror: {line}')
    if proc.returncode != 0:
        raise RuntimeError(f'a2til mirror failed ({proc.returncode})')
    return proc.stdout.splitlines()


def strip_volume(root):
    removed, kept = [], []

    def rm_recursive(path, entry):
        if entry.is_dir():
            for child in list(prodos.scandir(path)):
                rm_recursive(f'{path}/{child.name}', child)
            prodos.rmdir(path)
        else:
            prodos.remove(path)

    for entry in list(prodos.scandir(root)):
        if entry.name.upper() == 'PRODOS':
            kept.append(entry.name)
            continue
        rm_recursive(f'{root}/{entry.name}', entry)
        removed.append(entry.name)
    return kept, removed


def main():
    if CORP.IMG_DIR != f'/mnt/{CARRIER_VOL}/E2E':
        print(f'error: src/test/e2etestb.s hardwires the script path '
              f'{CORP.IMG_DIR}/SCRIPT, which does not match carrier volume '
              f'{CARRIER_VOL}', file=sys.stderr)
        return 2
    missing = []
    for path, label in ([(CARRIER_IMG, 'carrier volume'),
                         (KERNEL_BIN, 'vendored ProDOS kernel'),
                         (SYS_BIN, 'MAUXE2E.SYSTEM')]
                        + [(os.path.join(BUILD, f'{t}.bin'), f'{t} binary')
                           for t in NEEDED]):
        if not os.path.exists(path):
            missing.append(f'{label}: {path}')
    if missing:
        for m in missing:
            print(f'error: missing {m}', file=sys.stderr)
        print('       (`make check-userland` builds the utilities -- '
              '`make` alone does not)', file=sys.stderr)
        return 2

    # A fresh mirror pair every build: a stale sidecar describing a
    # previous run's outputs would make this pass read as a conflict.
    shutil.rmtree(MIRRORDIR, ignore_errors=True)
    shutil.rmtree(HOSTDIR, ignore_errors=True)
    CORP.write_host_corpus(HOSTDIR)
    staged = CORP.write_mirror_stage(MIRRORDIR)

    # A fresh, larger volume rather than a copy of the carrier -- see
    # VOL_BLOCKS.  a2til's `create` formats an EMPTY volume, so blocks 0
    # and 1 (the ProDOS boot loader, the one thing on the carrier that is
    # not a file) are spliced across from the carrier verbatim; the boot
    # loader's only job is to find and load `PRODOS` out of the volume
    # directory, which is size-independent.
    prodos.create(OUT_IMG, name=CARRIER_VOL, blocks=VOL_BLOCKS)
    with open(CARRIER_IMG, 'rb') as f:
        boot = f.read(BOOT_BYTES)
    if len(boot) != BOOT_BYTES or boot == bytes(BOOT_BYTES):
        print(f'error: {CARRIER_IMG} has no boot block to copy',
              file=sys.stderr)
        return 2
    with open(OUT_IMG, 'r+b') as f:
        f.write(boot)

    prodos.mount(OUT_IMG)
    root = f'/mnt/{CARRIER_VOL}'
    kept, removed = strip_volume(root)

    with open(KERNEL_BIN, 'rb') as f:
        prodos.write(f'{root}/PRODOS', f.read(), file_type=0xFF,
                     aux_type=0x2000, overwrite=True)
    with open(SYS_BIN, 'rb') as f:
        system = f.read()
    prodos.write(f'{root}/MAUX.SYSTEM', system, file_type=0xFF,
                 aux_type=0x2000, overwrite=True)
    sizes, shas = {}, {}
    prodos.mkdir(f'{root}/BIN')
    for tool in NEEDED:
        with open(os.path.join(BUILD, f'{tool}.bin'), 'rb') as f:
            data = f.read()
        sizes[tool] = len(data)
        shas[tool] = hashlib.sha256(data).hexdigest()[:12]
        prodos.write(f'{root}/BIN/{tool.upper()}', data, file_type=0x06,
                     aux_type=0x0800, overwrite=True)
    prodos.mkdir(CORP.IMG_DIR)
    prodos.unmount(CARRIER_VOL)

    mirror(OUT_IMG, CORP.IMG_DIR, MIRRORDIR, 'build-e2e')

    vol = prodos.Volume(OUT_IMG, readonly=True)
    try:
        entries = list(vol.scandir(CORP.IMG_DIR))
        free, total = vol.free_blocks, vol.total_blocks
    finally:
        vol.close()

    print(f'[build-e2e] carrier={CARRIER_IMG} volname={CARRIER_VOL}')
    print(f'[build-e2e] kept={kept} removed={removed}')
    # SIZE IS NOT IDENTITY.  A one-opcode change -- `bcc` to `bra`, say
    # -- leaves the byte count identical, so a size table cannot tell a
    # stale .bin from a fresh one.  This cost a vacuous sabotage on
    # 2026-08-23: `make check-e2e` staged a `sum.bin` that predated the
    # edit to src/bin/sum.s (mtime granularity across a rapid stash/
    # rebuild/pop), the gate passed, and only a byte-compare against a
    # separately built binary showed why. Hash every staged binary so
    # the evidence is in the log rather than in someone's memory.
    print(f'[build-e2e] MAUX.SYSTEM {len(system)}B '
          f'{hashlib.sha256(system).hexdigest()[:12]}')
    for t in NEEDED:
        print(f'[build-e2e]   {t:6} {sizes[t]:6}B  sha256:{shas[t]}')
    print(f'[build-e2e] {len(CORP.FIXTURES)} fixtures + SCRIPT staged '
          f'through `a2til mirror --once --raw` -> {CORP.IMG_DIR} '
          f'({len(entries)} entries, {CORP.corpus_size()} bytes)')
    print(f'[build-e2e] {len(CORP.CASES)} cases; longest sh line '
          f'{max(len(c.sh_line()) for c in CORP.CASES)} of LINEMAX '
          f'{CORP.SH_LINEMAX}')
    if free is not None:
        print(f'[build-e2e] volume {free} of {total} blocks free before '
              f'the run')
    print(f'[build-e2e] {OUT_IMG} ready ({os.path.getsize(OUT_IMG)} bytes)')
    if len(entries) != len(staged):
        print(f'error: staged {len(staged)} files but the image holds '
              f'{len(entries)} -- the mirror pass did not land', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
