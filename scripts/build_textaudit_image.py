    tmp = tempfile.mkdtemp(prefix='maux-ta-nufx-')
    path = os.path.join(tmp, 'A.SHK')
    nufx.create(path, when=datetime.datetime(2026, 9, 21, 12, 0, 0))
    with nufx.NufxArchive(path, readonly=False) as arc:
        arc.write_file('/AAA.TXT', b'alpha\r', file_type=0x04,
                       aux_type=0x0000)
        arc.write_file('/BBB.BIN', b'\x01\x02\x03\x04',
                       file_type=0x06, aux_type=0x2000)
        arc.write_file('/CCC.REL', b'x' * 300, file_type=0xF8,
                       aux_type=0x0000)
    with open(path, 'rb') as fh:
        blob = fh.read()
    shutil.rmtree(tmp, ignore_errors=True)
    return blob


