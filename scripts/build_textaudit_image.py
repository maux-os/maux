def _uu6(v):
    return 0x60 if v == 0 else 0x20 + v


def uuenc_text(name, raw):
    """The historical uuencode(1) text of `raw`, as PLAIN (low-bit)
    lines -- staged through `lines()` above like every other text
    fixture in this file, so it lands on the image as ordinary maux
    text (high bit + CR) and reads back through uudecode's own
    GETLINE the same way. Mirrors src/bin/uuencode.s's SPLIT3/
    ENCODE6 from the algorithm's own definition, not a copy of the
    implementation under test (same posture as posixutil_cases2.py's
    own _uu_hist(), written independently)."""
    rows = [f'begin 644 {name}']
    i = 0
    n = len(raw)
    while i < n:
        chunk = raw[i:i + 45]
        m = len(chunk)
        chars = [chr(_uu6(m))]
        j = 0
        while j < m:
            b0 = chunk[j]
            b1 = chunk[j + 1] if j + 1 < m else 0
            b2 = chunk[j + 2] if j + 2 < m else 0
            chars.append(chr(_uu6(b0 >> 2)))
            chars.append(chr(_uu6(((b0 & 3) << 4) | (b1 >> 4))))
            chars.append(chr(_uu6(((b1 & 0x0F) << 2) | (b2 >> 6))))
            chars.append(chr(_uu6(b2 & 0x3F)))
            j += 3
        rows.append(''.join(chars))
        i += 45
    rows.append(chr(_uu6(0)))
    rows.append('end')
    return lines(*rows)
