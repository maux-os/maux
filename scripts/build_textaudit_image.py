def group_script(group):
    out = []
    for step in STEPS[group]:
        if step[0] == 'pair':
            out.append(step[2])
            out.append(step[3])
        elif step[0] != 'nopair':
            out.append(step[2])
    return ''.join(line + '\r' for line in out) + 'EXIT\r'


def repeat_pairs(group):
    """[(program, output 1, output 2)] the gate must compare."""
    return [(s[1], s[4], s[5]) for s in STEPS[group] if s[0] == 'pair']


