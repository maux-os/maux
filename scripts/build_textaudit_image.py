def group_files(group):
    """Data files a group's script reads: {NAME: (bytes, type, aux)}.

    The aux type is not decoration: for a REL object it IS the code
    length, and `ld` reads it from the directory entry.
    """
    common = {}
    if group == 'a':
        common['SEED'] = (SEED, 0x04)
        common['GREPIN'] = (GREPIN, 0x04)
        common['EDSCR1'] = (edscript('/mnt/MAUX/O/ED1'), 0x04)
        common['EDSCR2'] = (edscript('/mnt/MAUX/O/ED2'), 0x04)
    elif group == 'b':
        common['SEED'] = (SEED, 0x04)
        common['GREPIN'] = (GREPIN, 0x04)
        common['SORTIN'] = (SORTIN, 0x04)
        # $E0/$8002 is the ProDOS stamp for a ShrinkIt archive.
        common['NUFXIN'] = (NUFXIN, 0xE0)
        common['UNIQIN'] = (UNIQIN, 0x04)
        common['TRIN'] = (TRIN, 0x04)
        common['DIFFA'] = (DIFFA, 0x04)
        common['DIFFB'] = (DIFFB, 0x04)
        # A byte-identical COPY of DIFFA under a second name: `CMP X X`
        # cannot be used for the identical case because ProDOS refuses
        # the second OPEN of an already-open file, and cmp then
        # exercises its "cannot open" path instead of its compare loop.
        common['DIFFC'] = (DIFFA, 0x04)
        common['TAILIN'] = (TAILIN, 0x04)
        common['RWFILE'] = (lines('chmod target'), 0x04)
        # bpatch: a spec (bit-7-masked on read, so plain ASCII) and two
        # byte-identical targets carrying an LC switch to flip and a byte
        # to set. BPT1/BPT2 -> [AD 83 C0 EE] after BPSPEC.
        common['BPSPEC'] = (b'set 03 EE\rflip-lc\r', 0x04)
        common['BPT1'] = (bytes([0xAD, 0x81, 0xC0, 0x55]), 0x06)
        common['BPT2'] = (bytes([0xAD, 0x81, 0xC0, 0x55]), 0x06)
    elif group == 'd':
        common['CA'] = (CA, 0x04)
        common['CB'] = (CB, 0x04)
        common['DIFFA'] = (DIFFA, 0x04)
        common['DIFFB'] = (DIFFB, 0x04)
        common['TEEIN'] = (TEEIN, 0x04)
        common['RTLIB'] = (RTLIB_REL, 0xF8, 68)
        common['RTMAIN'] = (RTMAIN_REL, 0xF8, 4)
        common['EXSCR1'] = (edscript('/mnt/MAUX/O/EX1'), 0x04)
        common['EXSCR2'] = (edscript('/mnt/MAUX/O/EX2'), 0x04)
        # uudecode's own static input: the historical uuencode(1)
        # text of build/echo.bin, computed at BUILD TIME (not by a
        # PREP line spawning uuencode first) -- see this file's own
        # note by the uudecode PAIR below.
        with open(os.path.join(BUILD, 'echo.bin'), 'rb') as f:
            common['UDENC'] = (uuenc_text('UDENC', f.read()), 0x04)
    elif group == 'c':
        # A REL object is file type $F8 and its AUX TYPE is the CODE
        # LENGTH. `ld` reads that length from the directory entry, so
        # a REL staged with aux=0 links to a 0-byte output and every
        # comparison downstream is vacuous -- which is what happened
        # here first time. The numbers are build_nm_image.py's own,
        # for the same two real Merlin-8 2.59 objects.
        common['RTLIB'] = (RTLIB_REL, 0xF8, 68)
        common['RTMAIN'] = (RTMAIN_REL, 0xF8, 4)
        with open(GOODMOD_SRC, 'rb') as f:
            common['GOODMOD.S'] = (f.read(), 0x04)
        with open(MULTIMOD_SRC, 'rb') as f:
            common['MULTIMOD.S'] = (f.read(), 0x04)
        # A recipe line's first character must be a TAB (makeread.s);
        # a rule header is `target: prereq`. SEED is staged above for
        # groups a and b -- group c needs its own copy as the
        # prerequisite, which exists and so is never itself rebuilt.
        common['SEED'] = (SEED, 0x04)
        common['MKA'] = (makefile('/mnt/MAUX/O/MK1'), 0x04)
        common['MKB'] = (makefile('/mnt/MAUX/O/MK2'), 0x04)
        # man's own page, staged at /usr/man/MAN through the SAME
        # man_to_maux() transform build_play_image.py's own
        # stage_man_pages() applies -- this carrier has no man-pages
        # rule of its own, so `MAN MAN > {out}` would otherwise open
        # nothing and its PAIR would pass VACUOUSLY (two empty files
        # compare equal). See this group's own `man` PAIR comment.
        with open(os.path.join(BUILD, 'man', 'man.TXT'), 'rb') as f:
            common['USR/MAN/MAN'] = (man_to_maux(f.read()), 0x04)
        common['TSORTIN'] = (TSORTIN, 0x04)
        # join (2026-09-15): its own two sorted fixtures -- split/
        # csplit reuse GOODMOD.S above, no new staging needed.
        common['JOININ1'] = (JOININ1, 0x04)
        common['JOININ2'] = (JOININ2, 0x04)
        # patch (2026-09-17): the listing, and two identical targets.
        # PT1/PT2 -> alpha/BRAVO/charlie/delta/echo after PTSPEC. The
        # listing's own header names PT1, which the -i form never
        # consults (the operand decides) -- it is there so the file is
        # a real patch rather than a bare hunk.
        common['PTSPEC'] = (PTSPEC, 0x04)
        common['PT1'] = (PTA, 0x04)
        common['PT2'] = (PTA, 0x04)
    return common


def makefile(target):
    """One rule: build `target` from /mnt/MAUX/SEED by copying it.

    The recipe is a tab, then an absolute path -- see the note in
    STEPS['c'] for why both of those are load-bearing.
    """
    return script_bytes(f'{target}: /mnt/MAUX/SEED\r'
                        f'\t/bin/CP /mnt/MAUX/SEED {target}\r')


def image_path(group):
    return os.path.join(BUILD, f'textaud{group}.po')


def expected_paths(group):
    """{device path: program name} the audit must observe, for the
    vacuity guard. A gate that watches a run in which nothing spawned
    passes forever."""
    # PHYSICAL paths: the audit watches the kernel's own MLI opens.
    out = {f'/{CARRIER_VOL}/BIN/SH'.upper(): 'sh'}
    for name in GROUP_BINS[group]:
        out[f'/{CARRIER_VOL}/BIN/{name}'.upper()] = name
    return out


def build(group):
    binaries = [('sh', os.path.join(BUILD, 'sh.bin'))] + [
        (n, os.path.join(BUILD, f'{n}.bin')) for n in GROUP_BINS[group]]
    for path, label in [
        (CARRIER_IMG, 'carrier volume'),
        (KERNEL_BIN, 'vendored ProDOS kernel'),
        (SYS_BIN, 'MAUXSH.SYSTEM'),
    ] + [(p, f'{n} userland binary') for n, p in binaries]:
        if not os.path.exists(path):
            print(f'error: missing {label}: {path}', file=sys.stderr)
            return 2

    out_img = image_path(group)
    # An 800-block (400 KB) volume, not the 280-block carrier: group a
    # (the file/directory core) filled the carrier EXACTLY, and the
    # signal kernel's 791-byte growth (2026-09-02) tipped it to 0 free
    # -- every write in the script then failed "cannot redirect"
    # (learning:kernel bytes are volume bytes). Then 400 blocks went
    # the same way (2026-09-14): group d, with uuencode/uudecode's
    # five output files added, finished its run with ONE free block,
    # and the last file written -- uudecode's WARM pair -- lost its
    # close-time flush to ProDOS $48 (volume full) and came out 512 B
    # of 1244. That red was read as a stdio/warm-state bug for a whole
    # engineering session before an instrument at the exit stop
    # showed FCL_WERR=$48 and the bitmap showed 1 free block. A
    # volume-full write in THIS audit is always a space problem first
    # (report-volumes shows the margins). Same create+boot-copy
    # pattern build_fleet_image.py uses: a2til's `create` formats an
    # empty volume, so blocks 0-1 (the ProDOS boot loader, the one
    # bootable thing on the carrier) are copied over verbatim.
    prodos.create(out_img, name=CARRIER_VOL, blocks=800)
    with open(CARRIER_IMG, 'rb') as f:
        boot = f.read(1024)
    if len(boot) != 1024 or boot == bytes(1024):
        print(f'error: {CARRIER_IMG} has no boot block to copy',
              file=sys.stderr)
        return 2
    with open(out_img, 'r+b') as f:
        f.write(boot)
    prodos.mount(out_img)
    root = f'/mnt/{CARRIER_VOL}'

    with open(KERNEL_BIN, 'rb') as f:
        prodos.write(f'{root}/PRODOS', f.read(), file_type=0xFF,
                     aux_type=0x2000, overwrite=True)
    with open(SYS_BIN, 'rb') as f:
        prodos.write(f'{root}/MAUX.SYSTEM', f.read(), file_type=0xFF,
                     aux_type=0x2000, overwrite=True)

    # sh in the root (the harness spawns it by absolute path before any
    # PATH search exists); everything else in BIN, where sh's PATHTAB
    # looks first -- so every spawn is tagged /bin/<CMD>.
    prodos.mkdir(f'{root}/BIN')
    # Outputs go in a subdirectory: the volume directory is capped at
    # 51 entries by the formatter and cannot grow at runtime
    # (build_v1_system_image.py's own finding), and this script writes
    # more than that.
    prodos.mkdir(f'{root}/O')
    if group == 'c':
        # man's own page lives at /usr/man/MAN -- see group_files()'s
        # own note on this directory.
        prodos.mkdir(f'{root}/USR')
        prodos.mkdir(f'{root}/USR/MAN')
    total = 0
    for name, path in binaries:
        with open(path, 'rb') as f:
            data = f.read()
        total += len(data)
        target = f'{root}/BIN'
        prodos.write(f'{target}/{name}', data, file_type=0x06,
                     aux_type=0x0800, overwrite=True)

    for name, entry in group_files(group).items():
        data, ftype = entry[0], entry[1]
        aux = entry[2] if len(entry) > 2 else 0x0000
        prodos.write(f'{root}/{name}', data, file_type=ftype,
                     aux_type=aux, overwrite=True)
    # src/test/shtestb.s's PARENT_PROC opens /mnt/MAUX/OUT1 and /mnt/MAUX/OUT2
    # after `sh` exits (steps 3 and 4) and reports $EE if either is
    # missing -- it was written for check-sh, whose script creates them.
    # They are staged here instead of being written by the script so
    # that no group needs `echo` merely to satisfy the harness: the
    # program set per group is the audit's own subject and must not be
    # padded by the rig.
    for name in ('OUT1', 'OUT2'):
        prodos.write(f'{root}/{name}', lines(f'harness {name.lower()}'),
                     file_type=0x04, aux_type=0x0000, overwrite=True)
    script = script_bytes(group_script(group))
    prodos.write(f'{root}/SCRIPT', script, file_type=0x04, aux_type=0x0000,
                 overwrite=True)
    prodos.unmount(CARRIER_VOL)
    print(f'[build-textaudit] group {group}: {len(binaries)} binaries '
          f'({total} B), script {len(script)} B, {out_img} ready '
          f'({os.path.getsize(out_img)} B)')
    return 0


def main():
    groups = sys.argv[1:] or sorted(GROUP_BINS)
    for group in groups:
        if group not in GROUP_BINS:
            print(f'error: unknown group {group!r}', file=sys.stderr)
            return 2
        rc = build(group)
        if rc:
            return rc
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
