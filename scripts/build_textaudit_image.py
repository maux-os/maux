# ---------------------------------------------------------------------
# THE WORKLOADS -- what each program was actually made to DO. Read this
# table as the answer to the only question that decides whether a CLEAN
# verdict is worth anything, and to the second question this gate
# exists for: does the program still WORK when its bank comes back?
#
# Three step kinds:
#
#   PAIR  the same command, byte for byte, run TWICE ADJACENTLY into
#         two different output files. The second run is the warm
#         respawn -- lazy free hands it the first run's bank with the
#         first run's mutated text still in it -- and the two outputs
#         must be byte-identical. This is the repeat-with-identical-
#         arguments shape from learning:01M0MEKF0H8AVAXJG4PZ7P5QXC,
#         and it needs no expectation of its own: run 1 IS the
#         expectation. Adjacency is load-bearing -- an intervening
#         spawn can reclaim the bank and make run 2 cold, which passes
#         while proving nothing.
#   ONCE  a command that cannot be paired, WITH THE REASON. Every one
#         of these is a hole in the warm-respawn proof and is printed
#         as such by the gate.
#   PREP  scaffolding (making a file for `mv` to move). Not a claim.
# ---------------------------------------------------------------------
def PAIR(prog, template, base, out_dir='/mnt/MAUX/O'):
    return ('pair', prog,
            template.format(out=f'{out_dir}/{base}1'),
            template.format(out=f'{out_dir}/{base}2'),
            f'{out_dir}/{base}1', f'{out_dir}/{base}2')


def PAIRX(prog, line1, line2, out1, out2):
    return ('pair', prog, line1, line2, out1, out2)


def ONCE(prog, line, why):
    return ('once', prog, line, why)


def NOPAIR(prog, why):
    """State why a program has no repeat pair, adding NO script line.

    ONCE covers a program the script runs once because running it
    twice would not be a repeat. This covers the other case: a
    program the workload reaches only as ANOTHER program's child,
    where the script names it nowhere and adding a direct
    invocation would audit a different thing than the workload
    does.
    """
    return ('nopair', prog, None, why)


def PREP(line):
    return ('prep', '', line)


