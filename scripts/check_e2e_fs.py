#!/usr/bin/env python3
"""Run the T4 filesystem-tranche differential harness (`make check-e2e-fs`).

Boots the SAME parent process stage 1 uses (src/test/e2etest.s /
build/MAUXE2E.SYSTEM, CONTRACT sec 3.5 -- this tranche writes no 6502
assembly), pulls the two FLAT mirror pairs back with `a2til mirror`
(/mnt/MAUX/E2E's ST + /mnt/MAUX/OUT's Onn files), reads /mnt/MAUX/RO and
/mnt/MAUX/MUT back with the **`prodos` module directly** (mount/scandir/
read/unmount -- NEVER mirror, CONTRACT sec 3.0/3.2: mirror cannot recurse
into subdirectories and the two-way-mirror hazard is structurally
impossible only because those two directories are never handed to it),
compares, and reports.

THIS SCRIPT HOLDS NO EXPECTATIONS -- every "want" comes from a host
reference run moments earlier (Case.reference) or from the volume's own
directory entries read back by a2til (the VOL oracle).  docs/E2E.md sec 4:
no expected-output file in this corpus may be generated by running maux.

TL requirement (2026-08-23, CONTRACT sec 3.3): run `prodos.check()` --
a2til's full recursive volume integrity check (cross-linked/out-of-range
blocks, per-directory file_count, bitmap-vs-usage, the subdirectory $4A
popcount marker) -- AFTER the guest has finished mutating, and FAIL on any
problem.  A corpus that drives rm/mv/cp/mkdir against a real volume and
never checks it afterwards is leaving the most mechanical finding on the
table.

GUARD, added 2026-08-23 after the TL hit it directly on the rig: this
tranche's own headline property, CONTRACT sec 10.4's "mutating tools
have no idempotent re-run", applies to the GATE's own inputs, not only
to a case. `make check-e2e-fs` is safe -- its Makefile target rebuilds
the image first -- but invoking this script directly against an image
that has ALREADY been booted once fails SILENTLY and confidently wrong:
/mnt/MAUX/OUT already holds the previous run's Onn files, so a case that
produces no output this time is judged against last run's output;
/mnt/MAUX/E2E/ST is APPENDED to (`ECHO $? >>`), so its line count grows
across runs and the `len(statuses) == len(CASES)` check fires with a
confusing "sh did not finish the script" message instead of the real
one; and every /mnt/MAUX/MUT/Cnn tree has already been mutated, so
rm/mv/cp/mkdir cases run against POST-mutation state and get judged
against a `pre` snapshot that no longer describes what is on the
volume. `check_not_already_run()` below refuses outright, before the
emulator is ever started, rather than trying to repair the image --
a harness that patches its own inputs is one that can hide a real
failure. It does NOT also gate on the `.pre.json` sidecar's mtime
against the image's: a2til's `Volume.close()` (`~/src/a2til/a2til/
_backing.py`'s `flush()`) `msync`s the mmap on every unmount, including
`build_e2efs_image.py`'s own FINAL unmount, which runs AFTER that
script saves `PRE_SNAPSHOT` -- so a plain "image not newer than
snapshot" check would very plausibly flag a completely fresh, correct
build as stale. Said so rather than shipping an unverified check
(no emulator was booted to confirm this either way, per this task's
own constraints).
"""
