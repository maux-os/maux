#: E4's request, 2026-08-23: a2til `check()`'s problem strings already
#: name the offending PATH in prose (Volume.check()'s own `walk()` builds
#: messages like 'file /mnt/MAUX/MUT/C31/X: ...'); this maps a /mnt/MAUX/MUT/Cnn
#: prefix back to the CASE that owns that tree, so a corruption failure
#: names the case instead of starting a bisection.
_MUT_TREE_RE = re.compile(re.escape(FM.IMG_MUT) + r'/([A-Za-z][A-Za-z0-9.]*)')


def attribute_problem(problem):
    m = _MUT_TREE_RE.search(problem)
    if not m:
        return problem
    tree = m.group(1)
    cids = CORP.REGISTRY.tree_case.get(tree)
    if not cids:
        return problem
    label = f'case {cids[0]}' if len(cids) == 1 else f'cases {cids} (shared)'
    return f'{problem}  [tree {tree} owned by {label}]'


def check_not_already_run(disk):
    """TL finding, 2026-08-23 (see this file's own docstring): refuse to
    boot against an image that has already been run once. Mounts
    READ-ONLY (no write intent on an image we are about to hand to the
    emulator unmodified) and checks the two facts `build_e2efs_image.
    py`'s own final assertions guarantee of a freshly-built, never-
    booted image: `/mnt/MAUX/OUT` has 0 entries, and `/mnt/MAUX/E2E/ST` is 0
    bytes. Returns a list of problem strings; empty means "safe to
    boot". Never attempts to repair anything -- see the module
    docstring on why."""
    problems = []
    prodos.mount(disk, readonly=True)
    try:
        out_entries = list(prodos.scandir(FM.IMG_OUT))
        if out_entries:
            names = ', '.join(sorted(e.name for e in out_entries))
            problems.append(
                f'{FM.IMG_OUT} already has {len(out_entries)} entrie(s) '
                f'({names}) -- a freshly-built image starts with 0')
        st_path = f'{FM.IMG_CTL}/{FM.STATUS_NAME}'
        try:
            st_entry = prodos.stat(st_path)
        except (FileNotFoundError, KeyError):
            problems.append(f'{st_path} does not exist at all')
        else:
            if st_entry.eof != 0:
                problems.append(
                    f'{st_path} is {st_entry.eof} byte(s) -- a freshly-'
                    f'built image starts at 0 (`ECHO $? >>` APPENDS, so '
                    f'a nonzero length means this image has already run '
                    f'at least once)')
    finally:
        prodos.unmount(CARRIER_VOL)
    return problems


def peek_aux1(client, addr, count=1):
    return client.call_tool('peek', {
        'addr': addr, 'count': count, 'bank': 'aux', 'aux_bank': 1,
    })['bytes']


def pulled(mirrordir, name):
    """As scripts/check_e2e.py's pulled(): read a file `a2til mirror`
    pulled back, whatever suffix its ProDOS type earned it, and flag a
    non-#040000 suffix as information (maux did not create a TXT file)."""
    for candidate in (name, f'{name}#040000'):
        path = os.path.join(mirrordir, candidate)
        if os.path.exists(path):
            with open(path, 'rb') as fh:
                return fh.read(), None
    hits = sorted(glob.glob(os.path.join(mirrordir, f'{name}#*')))
    if not hits:
        return None, f'{name} was not created on the volume at all'
    with open(hits[0], 'rb') as fh:
        return fh.read(), (f'{name} came back as {os.path.basename(hits[0])} '
                           f'-- not a ProDOS TXT file')


def run_emulator(disk):
    env = dict(os.environ)
    env['VERILOGAPPLE_ROMS'] = ROMS_DIR
    client = MCPClient([SUPERVISOR], env)
    try:
        client.initialize()
        r = client.call_tool('reset', {'backend': 'fast'})
        print(f'[check-e2e-fs] reset -> {r}', file=sys.stderr)
        r = client.call_tool('mount_disk', {'path': os.path.abspath(disk)})
        print(f'[check-e2e-fs] mount_disk -> {r}', file=sys.stderr)
        if r.get('ok') is False:
            raise RuntimeError(f'mount_disk failed: {r}')
        t0 = time.time()
        done = 0
        for i in range(MAX_STEPS):
            client.call_tool('step', {'cycles': STEP_CYCLES})
            done = peek_aux1(client, R_DONE)[0]
            if done in (0xAA, 0xEE):
                break
        elapsed = time.time() - t0
        return {
            'done': done,
            'err': peek_aux1(client, R_ERR)[0],
            'step': peek_aux1(client, R_STEP)[0],
            'sh_pid': peek_aux1(client, R_SH_PID)[0],
            'sh_wait': peek_aux1(client, R_SH_WAIT)[0],
            'sh_status': peek_aux1(client, R_SH_STATUS)[0],
            'steps': i + 1,
            'seconds': elapsed,
        }
    finally:
        client.close()


def poststate_verdict(case, root, pristine_mut, terminal=None):
    """The SECOND, independent assertion CONTRACT sec 5.2 requires for
    poststate=True cases: the reference tree is a HOST copy of the
    pristine MUT tree with case.ref_op applied; the actual tree is the
    volume's own /mnt/MAUX/MUT/<tree> read back with e2e_fsmap.read_tree
    (never mirror).

    `pristine_mut` (NOT `HOSTDIR_MUT` directly) -- E7 integration bug
    found 2026-08-23: Case.reference() shells out to the REAL host tool
    for oracle='REF'/'REF+VOL' cases, and every one of
    e2e_fs_mutate.py's rm/mv/cp/mkdir cases is oracle='REF'. By the time
    this function runs (after case.reference() already executed for
    THIS case, in the main() loop below), HOSTDIR_MUT/<tree> has
    ALREADY been mutated by the real host rm/mv/cp/mkdir -- reading it
    as the pristine base and then applying ref_op AGAIN double-mutates
    it (for `rm`, this crashes: FileNotFoundError, removing a file the
    host reference already removed). `pristine_mut` is a copy of
    HOSTDIR_MUT taken ONCE, before the case loop runs any reference()
    call, exactly for this reason.

    B3 FIX, 2026-08-23: `terminal` (e2e_fs_common.terminal_cids()'s
    output, or None to skip the guard) -- `want_tree` is already built
    CUMULATIVELY up to and including THIS case via
    apply_tree_seq_ref_op, so it is always the right EXPECTATION. But
    `got_tree` below reads the LIVE volume AFTER THE WHOLE RUN, same as
    Volume.post/.post_at's own single-final-snapshot limitation (see
    that method's docstring) -- for a poststate=True case that is NOT
    its own tree_seq= group's runnable-terminal member, the actual
    on-disk tree reflects LATER group members' mutations too, not just
    this one's. No current case combines tree_seq= with poststate=True
    (grep: e2e_fs_mutate.py's own trees are all exclusive), so this
    guard is dormant today -- added for the same architectural reason
    as Volume.post_at's fix, not because a live case needs it yet."""
    if case.tree is None:
        return False, 'poststate=True but no tree= -- nothing to read back'
    if case.tree_seq and terminal is not None and case.cid not in terminal:
        return True, ('REDUCED: poststate tree comparison NOT VERIFIED for '
                      'this step -- a real single-final-snapshot run '
                      'reads the volume only after the WHOLE script '
                      'finishes, so a non-terminal tree_seq= member\'s own '
                      'mid-sequence tree state is unobservable (see '
                      'Volume.post_at\'s docstring); the case\'s stdout/'
                      'exit-status assertion, already checked before this '
                      'function runs, is unaffected')
    src = os.path.join(pristine_mut, case.tree)
    with tempfile.TemporaryDirectory() as scratch:
        dst = os.path.join(scratch, case.tree)
        shutil.copytree(src, dst)
        # TL ruling 2026-08-23: for a tree_seq= group, ref_op callables
        # apply CUMULATIVELY, in cid order, up to and including THIS
        # case -- not just this case's own ref_op in isolation. For an
        # exclusive tree this degrades to the single ref_op it always
        # was.
        FC.apply_tree_seq_ref_op(CORP.REGISTRY, case, dst)
        # CONTRACT sec 7.3's 'changed ProDOS file type' rejection --
        # FC.merged_types_for_tree (E8, 2026-08-23) is
        # types_for_tree()'s pre-state dict PLUS case.expect_types
        # resolved against that same pre-state snapshot, so a
        # moved/copied/renamed destination's type is checked too, not
        # just a survivor at its original relpath. See
        # types_for_tree()'s own docstring for the gap this closes.
        types = FC.merged_types_for_tree(CORP.REGISTRY, case)
        # THE ENCODING BOUNDARY (docs/E2E.md sec 9.5; TL fix,
        # 2026-08-23) -- FC.merged_kinds_for_tree's exact sibling to
        # merged_types_for_tree above, for host_tree()'s kinds=
        # argument: without this, `want_tree` carried HOST-native bytes
        # (LF, low-ASCII) while `got_tree` below (e2e_fsmap.read_tree)
        # carries IMAGE bytes (high-bit, $8D) for every 'text'-kind
        # fixture, and ANY case with a surviving/copied/moved text file
        # false-red -- reproduced on a scratch volume: MUT03/KEEP
        # compared b'keep me\n' against
        # b'\xeb\xe5\xe5\xf0\xa0\xed\xe5\x8d'. See host_tree()'s own
        # docstring and the module comment above e2e_fs_common.
        # compare_tree for the full argument.
        kinds = FC.merged_kinds_for_tree(CORP.REGISTRY, case)
        want_tree = FC.host_tree(dst, types=types, kinds=kinds)
    got_tree = FM.read_tree(f'{FM.IMG_MUT}/{case.tree}')
    return FC.compare_tree(want_tree, got_tree)


def main():
    disk = sys.argv[1] if len(sys.argv) > 1 else DISK

    errs, dead = CORP.REGISTRY.check_citations()
    for e in errs:
        print(f'[check-e2e-fs] FAIL: {e}', file=sys.stderr)
    for d in dead:
        print(f'[check-e2e-fs] FAIL: divergence entry {d} is cited by no '
             f'case -- the ratchet only tightens; delete it or use it',
             file=sys.stderr)
    if errs or dead:
        return 1

    # TL ruling 2026-08-23: print which cases share which tree, in
    # order, so the sharing is visible in the gate log rather than
    # implicit -- an exclusive (single-owner) tree is not printed here.
    for tree, cids in CORP.REGISTRY.tree_groups():
        print(f'[check-e2e-fs] shared tree {tree}: cases {cids} '
             f'(tree_seq=True, cumulative ref_op, contiguous cid order)')

    # T4 E9, 2026-08-23: print every case withheld from the generated
    # script because it HANGS the guest -- see e2e_fs_corpus.
    # HANG_QUARANTINE's own module-level comment for the measured
    # mechanism. Printed by NAME on every run, never a silent skip (a
    # case that quietly does not run is worse than one that fails).
    print(f'[check-e2e-fs] HANG QUARANTINE: {len(CORP.HANG_QUARANTINE)} '
         f'case(s) withheld from the generated script')
    for cid, (tool, reason) in sorted(CORP.HANG_QUARANTINE.items()):
        print(f'[check-e2e-fs]   HANG QUARANTINE case {cid} ({tool}): '
             f'{reason}')

    if not os.path.exists(SUPERVISOR):
        print(f'error: mcp_supervisor not found at {SUPERVISOR}', file=sys.stderr)
        return 2
    for path, what in ((disk, 'run `make e2efs-image` first'),
                       (HOSTDIR_RO, 'host RO fixtures'),
                       (HOSTDIR_MUT, 'host MUT fixtures'),
                       (MIRRORDIR_CTL, 'ctl mirror staging directory'),
                       (MIRRORDIR_OUT, 'out mirror staging directory'),
                       (PRE_SNAPSHOT, 'volume.pre snapshot -- run '
                                     '`make e2efs-image` again if this '
                                     'predates its introduction')):
        if not os.path.exists(path):
            print(f'error: {path} not found -- {what}', file=sys.stderr)
            return 2

    # TL guard, 2026-08-23 (see module docstring): refuse an
    # already-run image OUTRIGHT, before the emulator is ever started.
    already_run = check_not_already_run(disk)
    if already_run:
        print(f'error: {disk} has already been run once -- this '
             f'harness cannot safely re-run against it (CONTRACT sec '
             f'10.4: mutating tools have no idempotent re-run, and '
             f'that applies to this GATE\'s own inputs too):',
             file=sys.stderr)
        for p in already_run:
            print(f'  {p}', file=sys.stderr)
        print(f'  fix: run `make e2efs-image` to rebuild a fresh image '
             f'(or `make check-e2e-fs`, whose Makefile target does '
             f'this for you)', file=sys.stderr)
        return 2

    state = run_emulator(disk)
    print(f"[check-e2e-fs] done=${state['done']:02X} err=${state['err']:02X} "
         f"step=${state['step']:02X} sh_pid={state['sh_pid']} "
         f"sh_wait={state['sh_wait']} sh_status=${state['sh_status']:02X} "
         f"({state['steps']} x {STEP_CYCLES} cycles, {state['seconds']:.1f}s)")

    boot_failures = []
    if state['done'] != 0xAA:
        boot_failures.append(
            f"the harness process did not finish (done=${state['done']:02X}, "
            f"err=${state['err']:02X}, step={state['step']})")
    if state['err'] != 0:
        boot_failures.append(f"R_ERR expected $00, got ${state['err']:02X}")
    if state['sh_pid'] == 0:
        boot_failures.append('SPAWN(SH) returned pid 0')
    if state['sh_wait'] != state['sh_pid']:
        boot_failures.append(
            f"wait pid {state['sh_wait']} != spawn pid {state['sh_pid']}")
    if boot_failures:
        for f in boot_failures:
            print(f'[check-e2e-fs] FAIL: {f}', file=sys.stderr)
        return 1

    # TL item 4: surface the boot's own SPAWN(SH) pid onto every case, so
    # a `ps` invariant can assert it against a SECOND, independent kernel
    # route (the pid `ps` itself prints) rather than degrading to a
    # weaker heuristic.
    for case in CORP.CASES:
        case.spawn_pid = state['sh_pid']

    # -- pull the two FLAT mirror pairs back -----------------------------
    from build_e2efs_image import mirror
    mirror(disk, FM.IMG_CTL, MIRRORDIR_CTL, 'check-e2e-fs-ctl')
    mirror(disk, FM.IMG_OUT, MIRRORDIR_OUT, 'check-e2e-fs-out')

    notes = []
    status_bytes, note = pulled(MIRRORDIR_CTL, FM.STATUS_NAME)
    if status_bytes is None:
        print(f'[check-e2e-fs] FAIL: {note}', file=sys.stderr)
        return 1
    if note:
        notes.append(note)
    statuses_text, sp = C.decode_maux_text(status_bytes)
    if sp:
        print(f'[check-e2e-fs] FAIL: the exit-status log has {len(sp)} '
             f'byte(s) with bit 7 clear', file=sys.stderr)
        return 1
    try:
        statuses = [int(x) for x in statuses_text.split()]
    except ValueError:
        print(f'[check-e2e-fs] FAIL: unparseable exit-status log '
             f'{statuses_text!r}', file=sys.stderr)
        return 1
    if len(statuses) != len(CORP.CASES):
        print(f'[check-e2e-fs] FAIL: the exit-status log has {len(statuses)} '
             f'entries for {len(CORP.CASES)} cases -- `sh` did not run the '
             f'whole script (statuses: {statuses})', file=sys.stderr)
        return 1

    # -- read /mnt/MAUX/RO and /mnt/MAUX/MUT back with prodos, NEVER mirror ---
    prodos.mount(disk)
    root = f'/mnt/{CARRIER_VOL}'
    pristine_mut_root = None
    try:
        # TL requirement: full recursive integrity check AFTER the guest
        # has mutated the volume.
        problems = prodos.check(root)
        if problems:
            print(f'[check-e2e-fs] FAIL: a2til check() found '
                 f'{len(problems)} volume integrity problem(s) after the '
                 f'run:', file=sys.stderr)
            for p in problems:
                print(f'[check-e2e-fs]   {attribute_problem(p)}', file=sys.stderr)
            return 1
        print('[check-e2e-fs] a2til check(): volume sound after the run '
             '(no cross-linked/out-of-range blocks, no file_count '
             'mismatch, no bitmap disagreement, no $4A-risk subdirectory '
             'marker)')

        # TL item 3: volume.pre (persisted at build time) + volume.post
        # (taken now, before unmount) -- comparators get BOTH, because a
        # read-modify-write proof (chmod's whole value) needs a before
        # AND an after picture; a post-run read alone cannot show that
        # every OTHER GET_FILE_INFO field survived untouched.
        pre_snap = FC.VolumeSnapshot.load(PRE_SNAPSHOT)
        post_snap = FC.VolumeSnapshot(FM.snapshot_volume(root))

        # B3 FIX, 2026-08-23: which cids are safe to judge against the
        # single `.post` snapshot above -- see e2e_fs_common.terminal_
        # cids/Volume.post_at's own docstrings for why a real run (one
        # boot, one post-run mount) cannot give every tree_seq= case its
        # own step's state. `runnable_cids` is CORP.CASES's own cids
        # (HANG_QUARANTINE already applied -- exactly what this boot
        # actually ran), not ALL_CASES: a case withheld from the
        # generated script never mutated anything for real, so it must
        # not count as a "later" mutator when deciding another case's
        # terminality.
        runnable_cids = {c.cid for c in CORP.CASES}
        terminal = FC.terminal_cids(CORP.REGISTRY, runnable_cids)
        reduced = FC.reduced_assertion_cases(CORP.REGISTRY, runnable_cids)
        print(f'[check-e2e-fs] REDUCED ASSERTION table: {len(reduced)} '
             f'tree_seq= case(s) whose post-mutation volume state cannot '
             f'be verified against this run\'s single whole-corpus '
             f'snapshot (their exit-status/stdout assertion is UNAFFECTED '
             f'-- see e2e_fs_common.Volume.post_at\'s docstring):')
        for cid, tool, tree, paths in reduced:
            print(f'[check-e2e-fs]   case {cid:3d} ({tool}, tree={tree}): '
                 f'path(s) {list(paths)} re-touched by a later case in '
                 f'this run')

        # image_path=disk: e2e_invariants.py's df comparator (CONTRACT
        # EXTENSION 2) reads the image FILE's own byte size as its
        # independent ground truth for total_blocks; see Volume's own
        # docstring on why this is not the same fact as anything a2til
        # parsed out of the volume header.
        volume = FC.Volume(pre=pre_snap, post=post_snap, root=root,
                           image_path=disk, group_terminal_cids=terminal)

        # See poststate_verdict's own docstring: a pristine copy of
        # HOSTDIR_MUT, taken BEFORE any case.reference() call below can
        # mutate it for real (rm/mv/cp/mkdir's REF-oracle host
        # invocations do exactly that).
        pristine_mut_root = tempfile.mkdtemp(prefix='e2efs-pristine-mut-')
        pristine_mut = os.path.join(pristine_mut_root, 'mut')
        shutil.copytree(HOSTDIR_MUT, pristine_mut)

        verdicts, ref_statuses = [], []
        oracle_counts = {}
        # TL restructuring, 2026-08-23 (docs/E2E.md sec 9.9's blocking
        # fix -- see e2e_fs_common.judge()'s own docstring for the full
        # mechanism): poststate and exit status are now computed for
        # EVERY case BEFORE judge() is called, never conditionally on
        # whether stdout already agrees. The old ordering (`if
        # case.poststate and v.ok:`) was the bug itself -- a
        # defect-pinned, silent-on-success mutating case (40/41/48/50)
        # has stdout agree TRIVIALLY, so poststate never ran and the
        # case was classified DEFECT-FIXED sight-unseen.
        for i, case in enumerate(CORP.CASES):
            oracle_counts[case.oracle] = oracle_counts.get(case.oracle, 0) + 1
            raw, note = pulled(MIRRORDIR_OUT, case.out_name)
            # -- NO_OUTPUT_PINS: cases whose symptom IS the missing
            # -- file, judged here because judge() never runs without
            # -- output to judge. Two-sided like every other ratchet:
            # -- absent is the pin, present means it is fixed.
            no_out = INV.NO_OUTPUT_PINS.get(case.case_id)
            if no_out and raw is None:
                verdicts.append(FC.Verdict(
                    case, True,
                    f'{case.out_name} absent, which IS the pinned defect',
                    kind='DEFECT'))
                ref_statuses.append(None)
                continue
            if no_out and raw is not None:
                verdicts.append(FC.Verdict(
                    case, False,
                    f'{case.out_name} EXISTS now -- the NO_OUTPUT_PINS entry '
                    f'for {case.case_id!r} appears fixed; delete it',
                    kind='DEFECT-FIXED'))
                ref_statuses.append(None)
                continue
            if raw is None:
                verdicts.append(FC.Verdict(case, False, note, kind='MISSING'))
                ref_statuses.append(None)
                continue
            if note:
                notes.append(note)
            ref_out, ref_err, ref_status, ref_extra = case.reference(
                HOSTDIR_RO, HOSTDIR_MUT)
            ref_statuses.append(ref_status)

            poststate_ok, poststate_detail = None, ''
            if case.poststate:
                # B2's ordering (compute BEFORE judge, never gated on
                # v.ok) carrying B3's terminal= : a non-terminal
                # tree_seq member must not be judged against a .post
                # snapshot taken after later steps mutated its path.
                poststate_ok, poststate_detail = poststate_verdict(
                    case, root, pristine_mut, terminal=terminal)

            got_status = statuses[i]
            status_checked, status_ok = FC.status_verdict(
                case, got_status, ref_status)

            v = FC.judge(case, raw, ref_out + ref_err, volume, HOSTDIR_RO,
                        CORP.REGISTRY.comparators, CORP.REGISTRY.defects,
                        status_ok=(status_ok if status_checked else None),
                        poststate_ok=poststate_ok,
                        poststate_detail=poststate_detail)

            # Non-defect cases: judge() does not fold poststate into
            # their verdict (only a defect-pinned case's classification
            # needed the fix) -- reuse the SAME poststate_ok/detail
            # already computed above (never recompute) to wrap a
            # stdout-agreeing-but-tree-wrong non-defect case exactly as
            # before this restructuring.
            if case.defect is None and case.poststate and v.ok and not poststate_ok:
                v = FC.Verdict(case, False,
                               f'stdout/exit matched, but the '
                               f'POSTSTATE tree comparison failed: '
                               f'{poststate_detail}', kind='POSTSTATE')
            verdicts.append(v)
    finally:
        prodos.unmount(CARRIER_VOL)
        if pristine_mut_root is not None:
            shutil.rmtree(pristine_mut_root, ignore_errors=True)

    # NOT e2e_compare.format_report: this tranche's Case has
    # status_ruled=/expect_status=, which stage 1's status loop cannot
    # express, so e2e_fs_common.format_report is its OWN version (see
    # that function's docstring), not a reuse.
    lines, nfail = FC.format_report(verdicts, statuses, ref_statuses)
    for line in lines:
        print(f'[check-e2e-fs] {line}', file=sys.stderr)
    for n in notes:
        print(f'[check-e2e-fs] note: {n}', file=sys.stderr)

    # TL item 2: which reference binary answered is provenance, printed
    # once, so a reader never has to guess whether /bin or /usr/bin
    # supplied a given tool's answer.
    for tool, resolved in sorted(FC.resolved_ref_tools().items()):
        print(f'[check-e2e-fs] reference tool: {tool:8} -> {resolved}')

    print(f'[check-e2e-fs] oracle usage: ' +
         ', '.join(f'{o} {n}' for o, n in sorted(oracle_counts.items())))
    # `sorted(...)` bare would raise TypeError here: INVARIANTS keys are
    # USUALLY a plain name string, but e2e_fs_idiom.py registers one
    # legitimately-tuple key -- ('*', 'idiom case word resolved to
    # something other than sh itself') -- for a property that is not any
    # single tool's. tuple < str has no ordering, so the mixed set threw
    # and took EVERYTHING BELOW WITH IT: the invariant/defect listings,
    # the divergence ratchet, the free-block floor at CONTRACT sec 4,
    # and the gate's own final PASS/FAIL return. Latent since the tuple
    # key was introduced -- unreachable while earlier `return`s fired
    # first, and found 2026-08-24 only because emptying the HANG
    # QUARANTINE let a run reach this line for the first time. Sort on a
    # normalised string so both key shapes order together.
    for key, (prop, why) in sorted(CORP.REGISTRY.invariants.items(),
                                   key=lambda kv: str(kv[0])):
        print(f'[check-e2e-fs] INVARIANT {key}: {prop}')
        print(f'[check-e2e-fs]   why no reference exists: {why}')
    for key, reason in sorted(CORP.REGISTRY.defects.items()):
        print(f'[check-e2e-fs] KNOWN DEFECT {key[0]}: {key[1]}')
        print(f'[check-e2e-fs]   {reason}')
    grades = {}
    for (tool, axis), (grade, _r) in CORP.REGISTRY.divergence.items():
        grades[grade] = grades.get(grade, 0) + 1
    print(f'[check-e2e-fs] divergence ratchet: ' +
         ', '.join(f'{g} {n}' for g, n in sorted(grades.items())))

    vol = prodos.Volume(disk, readonly=True)
    try:
        free, total = vol.free_blocks, vol.total_blocks
    finally:
        vol.close()
    print(f'[check-e2e-fs] volume {free} of {total} blocks free after the run')
    if free < MIN_FREE_AFTER_RUN:
        print(f'[check-e2e-fs] FAIL: only {free} blocks free after the '
             f'run, need at least {MIN_FREE_AFTER_RUN} (CONTRACT sec 4)',
             file=sys.stderr)
        return 1

    if nfail:
        print(f'[check-e2e-fs] FAIL: {nfail} of {len(CORP.CASES)} cases '
             f'diverge from the host/volume reference with no ratchet '
             f'entry explaining it', file=sys.stderr)
        return 1
    npin = sum(1 for v in verdicts if v.kind == 'DEFECT')
    print(f'[check-e2e-fs] PASS: {len(CORP.CASES) - npin} cases agree with '
         f'their declared oracle; {npin} pinned to a KNOWN DEFECT above; '
         f'{len(CORP.HANG_QUARANTINE)} withheld by the HANG QUARANTINE '
         f'above (of {len(CORP.ALL_CASES)} defined total)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
